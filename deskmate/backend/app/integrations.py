"""成员 C 模块的依赖注入边界，仅定义平台需要的接口，不实现健康算法。"""

from typing import Any, Protocol


class WellbeingEngine(Protocol):
    def on_minute_stats(
        self, stat: dict[str, Any], current_focus: dict[str, Any] | None, env_temp: float
    ) -> Any: ...
    def check_flow_extension(self, focus_session_id: int) -> bool: ...
    def on_user_left(self, is_locked: bool) -> None: ...
    def generate_daily_report(self, date_str: str) -> dict[str, Any]: ...
